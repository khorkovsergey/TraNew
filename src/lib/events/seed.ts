/**
 * Materialises the catalogue against a supplied clock. The caller owns "now" so
 * a page, a test and a verification script can all agree on what is upcoming.
 */
/**
 * The instant at which the wall clock in `timeZone` reads `hour` on that day.
 *
 * Needed because `startHour` in the fixtures is the local time an organizer would
 * write on a poster — "18:00" for an evening webinar in Nicosia. Treating it as
 * UTC made every event three hours late in summer, which is the kind of error
 * that looks like a formatting choice rather than a wrong number.
 *
 * Approximate at the exact moment of a DST transition, which no fixture uses.
 */
function localInstant(dayMs: number, hour: number, timeZone: string): Date {
  const guess = new Date(dayMs + hour * HOUR);
  const inZone = new Date(guess.toLocaleString('en-US', { timeZone }));
  const inUtc = new Date(guess.toLocaleString('en-US', { timeZone: 'UTC' }));

  return new Date(guess.getTime() - (inZone.getTime() - inUtc.getTime()));
}

export function seedEvents(now: Date): TradingEvent[] {
  const midnight = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate());

  return SEEDS.map((seed) => {
    const { inDays, startHour, durationHours, ...event } = seed;
    const start = localInstant(midnight + inDays * DAY, startHour, event.timezone);
    const end = new Date(start.getTime() + durationHours * HOUR);
    const created = new Date(start.getTime() - 30 * DAY);

    return {
      ...event,
      startsAt: start.toISOString(),
      endsAt: end.toISOString(),
      createdAt: created.toISOString(),
      updatedAt: created.toISOString(),
      publishedAt: event.status === 'draft' ? null : created.toISOString(),
    } satisfies TradingEvent;
  });
}

export function seedOrganizer(id: string): Organizer | null {
  return SEED_ORGANIZERS.find((organizer) => organizer.id === id) ?? null;
}

export function seedOrganizerBySlug(slug: string): Organizer | null {
  return SEED_ORGANIZERS.find((organizer) => organizer.slug === slug) ?? null;
}

function agenda(items: Array<[string, string, string | null, string]>) {
  return items.map(([time, title, speaker, kind], index) => ({
    id: `ag_${index}`,
    time,
    title,
    speaker,
    kind,
    position: index,
  }));
}

function speakers(items: Array<[string, string, string, string | null]>) {
  return items.map(([initials, name, role, company], index) => ({
    id: `sp_${index}`,
    initials,
    name,
    role,
    company,
    avatarUrl: null,
    position: index,
  }));
}

